using System;
using System.Drawing;
using System.Windows.Forms;

namespace DCE_Manager
{
    // Mini-fenêtre "Launch options" : s'ouvre par un clic droit sur l'icône ▶ (First Mission) de la grille
    // des campagnes, en mode CampaignMaker seulement. Les options ne valent que pour CE lancement :
    // rien n'est mémorisé, rien n'est écrit sur disque. Pour l'instant il n'y en a qu'une (scan du relief).
    // Texte visible = anglais simple. Construite en code, comme les autres petites fenêtres (pas de .Designer.cs).
    public class LaunchOptions_Form : Form
    {
        private readonly CheckBox _chkScanRelief;

        // Vrai si l'option est cochée au moment du clic sur "Launch" (toujours décochée à l'ouverture).
        public bool ScanRelief
        {
            get { return _chkScanRelief.Checked; }
        }

        public LaunchOptions_Form(string campaignName)
        {
            Text = "Launch options - " + campaignName;
            FormBorderStyle = FormBorderStyle.FixedDialog;
            StartPosition = FormStartPosition.CenterParent;
            MinimizeBox = false;
            MaximizeBox = false;
            ShowInTaskbar = false;
            ClientSize = new Size(460, 168);

            var lblInfo = new Label
            {
                Text = "These options are used for this launch only. Nothing is remembered.",
                Left = 14,
                Top = 14,
                Width = 432,
                Height = 20
            };

            _chkScanRelief = new CheckBox
            {
                Text = "Scan the relief of the map",
                Left = 16,
                Top = 46,
                AutoSize = true,
                Checked = false
            };

            var lblHelp = new Label
            {
                Text = "Adds the relief scan (DCE_ScanRelief.lua) to the mission generated by this launch. You will rarely need it.",
                Left = 34,
                Top = 70,
                Width = 412,
                Height = 40,
                ForeColor = SystemColors.GrayText
            };

            var btnLaunch = new Button
            {
                Text = "Launch",
                Left = 262,
                Top = 124,
                Width = 90,
                DialogResult = DialogResult.OK
            };

            var btnCancel = new Button
            {
                Text = "Cancel",
                Left = 360,
                Top = 124,
                Width = 90,
                DialogResult = DialogResult.Cancel
            };

            var tip = new ToolTip { AutoPopDelay = 20000, InitialDelay = 300, ShowAlways = true };
            tip.SetToolTip(_chkScanRelief, "SCAN THE RELIEF\nThe mission generated by this launch will also run the relief scan. The choice is used once, then forgotten.");

            Controls.AddRange(new Control[] { lblInfo, _chkScanRelief, lblHelp, btnLaunch, btnCancel });
            AcceptButton = btnLaunch;
            CancelButton = btnCancel;
        }
    }
}
